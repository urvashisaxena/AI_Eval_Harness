"""Model scorecard generation (Markdown and self-contained HTML)."""

from __future__ import annotations

import html

from .config import HarnessConfig
from .metrics.base import METRIC_INFO
from .regression import ComparisonReport
from .schema import RunResult

_ARROWS = {True: "▲", False: "▼"}


def _fmt(v: float | None) -> str:
    return "—" if v is None else f"{v:.3f}"


def _status(metric: str, report: ComparisonReport | None) -> str:
    if report is None:
        return "–"
    blocking = [f for f in report.findings if f.metric == metric and f.blocking]
    if blocking:
        return "❌ FAIL"
    warnings = [
        f for f in report.findings
        if f.metric == metric and f.kind == "regression" and not f.blocking
    ]
    return "⚠️ WARN" if warnings else "✅ PASS"


def _delta_str(metric: str, report: ComparisonReport | None) -> str:
    if report is None or metric not in report.deltas:
        return "—"
    delta = report.deltas[metric]
    if delta == 0:
        return "±0.000"
    info = METRIC_INFO.get(metric)
    hib = info.higher_is_better if info else True
    good = (delta > 0) == hib
    return f"{_ARROWS[delta > 0]} {delta:+.3f}" + ("" if good else " (worse)")


def _worst_cases(run: RunResult, limit: int = 5) -> list[tuple[str, str, float]]:
    """(case_id, metric, value) for the weakest case scores, direction-aware."""
    rows = []
    for case in run.cases:
        for name, score in case.scores.items():
            info = METRIC_INFO.get(name)
            hib = info.higher_is_better if info else True
            badness = (1 - score.value) if hib else score.value
            rows.append((badness, case.case_id, name, score.value))
    rows.sort(reverse=True)
    return [(cid, m, v) for badness, cid, m, v in rows[:limit] if badness > 0]


def render_markdown(
    run: RunResult,
    baseline: RunResult | None = None,
    report: ComparisonReport | None = None,
    config: HarnessConfig | None = None,
) -> str:
    config = config or HarnessConfig()
    lines: list[str] = []
    gate = "" if report is None else ("✅ **PASSED**" if report.passed else "❌ **FAILED**")

    lines += [
        f"# Model Scorecard — {run.label}",
        "",
        f"| | |",
        f"|---|---|",
        f"| Run ID | `{run.run_id}` |",
        f"| Model under test | `{run.model}` |",
        f"| Judge | `{run.judge}` |",
        f"| Dataset | `{run.dataset_path}` (`{run.dataset_sha256[:12]}…`) |",
        f"| Cases | {run.metadata.get('num_cases', len(run.cases))} |",
        f"| Evaluated at | {run.created_at} |",
    ]
    if baseline is not None:
        lines.append(f"| Baseline | `{baseline.run_id}` ({baseline.label}) |")
    if gate:
        lines.append(f"| Governance gate | {gate} |")
    lines += ["", "## Metrics", ""]

    lines.append("| Metric | Value | Baseline | Δ | Threshold | Status |")
    lines.append("|---|---:|---:|---|---|---|")
    for metric, value in run.metrics.items():
        info = METRIC_INFO.get(metric)
        base_v = baseline.metrics.get(metric) if baseline else None
        t = config.thresholds.get(metric)
        parts = []
        if t:
            if t.min is not None:
                parts.append(f"min {t.min}")
            if t.max is not None:
                parts.append(f"max {t.max}")
            if t.max_regression is not None:
                parts.append(f"reg ≤ {t.max_regression}")
        direction = "" if info is None or info.higher_is_better else " ↓"
        lines.append(
            f"| {metric}{direction} | {_fmt(value)} | {_fmt(base_v)} "
            f"| {_delta_str(metric, report)} | {', '.join(parts) or '—'} "
            f"| {_status(metric, report)} |"
        )
    lines += ["", "_Metrics marked ↓ are lower-is-better._", ""]

    if report and report.findings:
        lines += ["## Findings", ""]
        for f in report.findings:
            icon = "❌" if f.blocking else ("📈" if f.kind == "improvement" else "⚠️")
            lines.append(f"- {icon} {f.message}")
        lines.append("")

    worst = _worst_cases(run)
    if worst:
        lines += ["## Weakest case scores", "", "| Case | Metric | Value |", "|---|---|---:|"]
        lines += [f"| `{cid}` | {m} | {v:.3f} |" for cid, m, v in worst]
        lines.append("")

    lines += [
        "---",
        f"_Generated by evalharness. Metric definitions: "
        + "; ".join(
            f"**{name}** — {info.description}"
            for name, info in METRIC_INFO.items()
            if name in run.metrics
        )
        + "_",
        "",
    ]
    return "\n".join(lines)


def render_html(
    run: RunResult,
    baseline: RunResult | None = None,
    report: ComparisonReport | None = None,
    config: HarnessConfig | None = None,
) -> str:
    """Self-contained HTML wrapper around the markdown content (simple,
    dependency-free rendering — tables and headings only)."""
    md = render_markdown(run, baseline, report, config)
    body = _markdown_tables_to_html(md)
    return f"""<!doctype html>
<html><head><meta charset="utf-8">
<title>Model Scorecard — {html.escape(run.label)}</title>
<style>
 body {{ font-family: -apple-system, Segoe UI, sans-serif; max-width: 900px;
        margin: 2rem auto; padding: 0 1rem; color: #1a1a2e; }}
 table {{ border-collapse: collapse; margin: 1rem 0; width: 100%; }}
 th, td {{ border: 1px solid #d0d0e0; padding: 6px 10px; text-align: left; }}
 th {{ background: #f0f0f8; }}
 code {{ background: #f4f4f8; padding: 1px 5px; border-radius: 4px; }}
 h1 {{ border-bottom: 2px solid #d0d0e0; padding-bottom: .4rem; }}
</style></head><body>
{body}
</body></html>
"""


def _markdown_tables_to_html(md: str) -> str:
    out: list[str] = []
    in_table = False
    for line in md.splitlines():
        stripped = line.strip()
        if stripped.startswith("|") and stripped.endswith("|"):
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            if all(set(c) <= {"-", ":", " "} and c for c in cells):
                continue  # separator row
            if not in_table:
                out.append("<table>")
                in_table = True
                tag = "th"
            else:
                tag = "td"
            row = "".join(f"<{tag}>{_inline(c)}</{tag}>" for c in cells)
            out.append(f"<tr>{row}</tr>")
            continue
        if in_table:
            out.append("</table>")
            in_table = False
        if stripped.startswith("# "):
            out.append(f"<h1>{_inline(stripped[2:])}</h1>")
        elif stripped.startswith("## "):
            out.append(f"<h2>{_inline(stripped[3:])}</h2>")
        elif stripped.startswith("- "):
            out.append(f"<p>• {_inline(stripped[2:])}</p>")
        elif stripped == "---":
            out.append("<hr>")
        elif stripped:
            out.append(f"<p>{_inline(stripped)}</p>")
    if in_table:
        out.append("</table>")
    return "\n".join(out)


def _inline(text: str) -> str:
    import re

    text = html.escape(text)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<!\w)_([^_]+)_(?!\w)", r"<em>\1</em>", text)
    return text
